-- Гостя в базе нет: гость - это просто человек, который не вошёл в аккаунт
CREATE TABLE users (
    id            BIGSERIAL PRIMARY KEY,          -- номер пользователя, растёт сам
    username      VARCHAR(50)  NOT NULL UNIQUE,   -- логин, не может повторяться
    password_hash VARCHAR(255) NOT NULL,          -- хеш пароля, не сам пароль
    created_at    TIMESTAMP    NOT NULL DEFAULT now()  -- когда зарегистрировался
);
